/**
 * One-off/reusable: extracts every citation from the live Wikipedia wikitext
 * and writes src/data/references.ts (imports fund.ts for the base URL).
 *
 * Usage: node scripts/parse-references.mjs [path-to-wikitext]
 * Default input: live fetch of the article's action=raw wikitext.
 */
import { writeFileSync, readFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

let wiki
if (process.argv[2]) {
  wiki = readFileSync(process.argv[2], 'utf8')
} else {
  wiki = await fetch(
    'https://en.wikipedia.org/w/index.php?title=PM_CARES_Fund&action=raw',
  ).then((r) => r.text())
}

function clean(value) {
  return value
    .replace(/\[\[([^\]|]*\|)?([^\]]*)\]\]/g, '$2')
    .replace(/\[([^\s\]]*)\s+[^\]]*\]/g, '$1')
    .replace(/'''?/g, '')
    .replace(/&amp;/g, '&')
    .trim()
}

function param(template, name) {
  // Prepend a pipe so the FIRST template parameter is also matched.
  const m = ('|' + template).match(new RegExp(`\\|\\s*${name}\\s*=\\s*([^|}]+)`))
  return m ? clean(m[1]) : ''
}

const refs = []
const defined = /<ref(?:\s+name="([^"]*)")?>([\s\S]*?)<\/ref>/g
let m
while ((m = defined.exec(wiki)) !== null) {
  const [, name, body] = m
  const cite = body.match(/\{\{[Cc]ite\s+\w+\|([\s\S]*?)\}\}/)
  if (!cite) continue
  const t = cite[1]
  const title = param(t, 'title')
  if (!title) continue
  refs.push({
    name: name ?? '',
    title,
    url: param(t, 'url'),
    work: param(t, 'work') || param(t, 'website') || param(t, 'newspaper') || param(t, 'agency') || param(t, 'publisher'),
    date: param(t, 'date'),
    accessDate: param(t, 'access-date'),
  })
}

const reuseCount = (wiki.match(/<ref\s+name="[^"]*"\s*\/>/g) ?? []).length

const header = `/**
 * AUTO-GENERATED by scripts/parse-references.mjs from the live Wikipedia
 * wikitext — do not hand-edit; regenerate instead.
 * Citations appear in article order (${refs.length} unique; ${reuseCount} additional in-text reuses).
 */
export interface Reference {
  title: string
  url: string
  work: string
  date: string
  accessDate: string
}

export const references: Reference[] = `

const body = JSON.stringify(
  refs.map(({ title, url, work, date, accessDate }) => ({
    title,
    url,
    work,
    date,
    accessDate,
  })),
  null,
  2,
)

const seeAlso = `
export const seeAlso = [
  { label: "Prime Minister's National Relief Fund", url: 'https://en.wikipedia.org/wiki/PMNRF' },
  { label: 'COVID-Crypto Relief Fund', url: 'https://en.wikipedia.org/wiki/COVID-Crypto_Relief_Fund' },
]
`

writeFileSync(resolve(root, 'src/data/references.ts'), header + body + '\n' + seeAlso)
console.log(`references.ts: wrote ${refs.length} unique citations (+${reuseCount} in-text reuses)`)
